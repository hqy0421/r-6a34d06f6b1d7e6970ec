# -*- coding: utf-8 -*-
"""生成样例来源工作簿（含跨月、部分还款、结清后多收、同日多笔、换利率）。

仅用于演示与自检，不是引擎的一部分：
    python3 -I make_sample_workbook.py <输出路径>
"""
import datetime
import sys
from collections import OrderedDict

import pyexcel

d = datetime.date

loans = [
    ["贷款编号", "借款人", "币种", "放款日", "本金_分", "年利率_基点"],
    # L001：10,000.00 元，3.65% 起，2/15 换 4.38%，3 月内部分还款后结清，
    #       结清当日再多收一笔（余款），另含一笔截止日后事件用于跳过登记。
    ["L001", "张三", "CNY", d(2026, 1, 10), 1_000_000, 3650],
    # L002：5,000.00 美元，7.30%，跨月部分还款，截止日仍未结清。
    ["L002", "李四", "USD", d(2026, 1, 20), 500_000, 7300],
    # L003：8,000.00 元，5.00%，同日两笔收款验证业务序号顺序。
    ["L003", "王五", "CNY", d(2026, 3, 1), 800_000, 5000],
]

rates = [
    ["贷款编号", "生效日", "新年利率_基点"],
    ["L001", d(2026, 2, 15), 4380],          # 3.65% -> 4.38%
    ["L001", d(2026, 7, 1), 5000],           # 晚于截止日，应被跳过
]

payments = [
    ["贷款编号", "收款日", "金额_分", "业务序号"],
    # L001：2 月部分还款（先息后本），3 月再还，3/20 结清，3/25 多收
    ["L001", d(2026, 2, 10), 50_000, 1],
    ["L001", d(2026, 3, 10), 200_000, 1],
    ["L001", d(2026, 3, 20), 10_000_000, 1],  # 超额付款，尾数进余款
    ["L001", d(2026, 3, 25), 5_000, 1],       # 已结清后的多收，全额余款
    ["L001", d(2026, 7, 5), 1_000, 1],        # 晚于截止日，跳过
    # L002：1 月底一笔、跨月 2 月一笔部分还款
    ["L002", d(2026, 1, 31), 100_000, 1],
    ["L002", d(2026, 2, 28), 150_000, 2],
    # L003：同日两笔，序号 2 先于 1 的录入顺序，引擎必须按序号处理
    ["L003", d(2026, 3, 15), 300_000, 2],
    ["L003", d(2026, 3, 15), 100_000, 1],
]

bookdict = OrderedDict([
    ("当前贷款", loans),
    ("利率变更", rates),
    ("收款", payments),
])


def main(path):
    pyexcel.save_book_as(bookdict=bookdict, dest_file_name=path)
    print("样例工作簿已写入:", path)


if __name__ == "__main__":
    main(sys.argv[1])
